export const getTranslation = (lang: string, key: string): string => {
  const dict = UI_STRINGS[lang] || UI_STRINGS['en'];
  return dict[key] || UI_STRINGS['en'][key] || key;
};

export const getConditionTranslation = (condition: string, lang: string): string => {
  if (lang === 'en') return condition;
  const match = CONDITION_TRANSLATIONS[condition];
  if (match && match[lang]) {
    return match[lang];
  }
  return condition;
};
